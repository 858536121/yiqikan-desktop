/** One build path for Metro (dev/native/export/OTA), CI, and browser tests. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ts = require('typescript');
const esbuild = require('esbuild');
const mobileRoot = path.resolve(__dirname, '..');
const sourceRoot = path.join(mobileRoot, 'src/webview');
const output = path.join(sourceRoot, 'generated/scripts.ts');
const formatHost = {
  getCanonicalFileName: file => file,
  getCurrentDirectory: () => mobileRoot,
  getNewLine: () => '\n',
};
function typecheck() {
  const config = ts.readConfigFile(path.join(sourceRoot, 'tsconfig.json'), ts.sys.readFile);
  if (config.error) throw new Error(ts.formatDiagnosticsWithColorAndContext([config.error], formatHost));
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, sourceRoot);
  const program = ts.createProgram(parsed.fileNames, parsed.options);
  const diagnostics = [...parsed.errors, ...ts.getPreEmitDiagnostics(program)];
  if (diagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, formatHost));
}
function compile(entry) {
  return esbuild.buildSync({
    absWorkingDir: mobileRoot,
    entryPoints: [path.join(sourceRoot, 'browser', entry)],
    bundle: true, write: false, platform: 'browser', format: 'iife', target: 'es2019',
    // Keep the page code readable; do not change its implicit globals or this binding.
    minify: false, legalComments: 'none', charset: 'utf8',
    tsconfig: path.join(sourceRoot, 'tsconfig.json'),
  }).outputFiles[0].text + '\ntrue;';
}
function expectedOutput() {
  typecheck();
  const scripts = { INJECTED_BEFORE_LOAD_SCRIPT: compile('early.ts'), INJECTED_SCRIPT: compile('runtime.ts') };
  return '// Generated by scripts/build-webview.cjs. Edit src/webview/browser; never edit this file.\n'
    + Object.entries(scripts).map(([name, script]) => `export const ${name}: string = ${JSON.stringify(script)};\n`).join('');
}
function writeChanged(content) {
  if (fs.existsSync(output) && fs.readFileSync(output, 'utf8') === content) return false;
  fs.mkdirSync(path.dirname(output), { recursive: true });
  const temporary = output + '.tmp-' + process.pid;
  fs.writeFileSync(temporary, content);
  fs.renameSync(temporary, output);
  return true;
}
function build({ check = false } = {}) {
  const content = expectedOutput();
  if (check) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content)
      throw new Error('WebView scripts are stale. Run pnpm --filter mobile build:webview.');
  } else writeChanged(content);
  return crypto.createHash('sha256').update(content).digest('hex');
}
let watcher;
function prepareForMetro() {
  build(); // Also runs for direct expo start/export, native Gradle/Xcode and OTA exports.
  if (watcher || (process.env.CI && !['0', 'false'].includes(process.env.CI.toLowerCase()))) return;
  let timer;
  watcher = fs.watch(sourceRoot, { recursive: true, persistent: false }, (_event, filename) => {
    if (!filename || !/^(browser[/\\].*\.ts|contracts\.ts|tsconfig\.json)$/.test(String(filename))) return;
    clearTimeout(timer);
    timer = setTimeout(() => {
      try { build(); }
      catch (error) {
        console.error('[WebView build]', error.message);
        // Invalidate the native module too: a failed edit must not silently run old code.
        writeChanged(`throw new Error(${JSON.stringify('WebView build failed:\n' + error.message)});\n`
          + 'export const INJECTED_BEFORE_LOAD_SCRIPT: string = "";\nexport const INJECTED_SCRIPT: string = "";\n');
      }
    }, 150);
  });
}
module.exports = { build, prepareForMetro };
if (require.main === module) {
  try { console.log('WebView scripts verified:', build({ check: process.argv.includes('--check') })); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
