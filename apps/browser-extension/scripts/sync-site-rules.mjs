import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
function output(file, content) {
  const target = new URL(file, root);
  if (check) {
    if (readFileSync(target, 'utf8') !== content) throw Error(`Regenerate ${file} with node scripts/sync-site-rules.mjs`);
  } else writeFileSync(target, content);
}
const source = readFileSync(new URL('../../../packages/shared/src/site-rules/page-script.ts', import.meta.url), 'utf8');
const body = source.match(/export const SITE_RULE_PAGE_SCRIPT = String\.raw`([\s\S]*)`;\s*$/)?.[1];
if (!body) throw Error('Shared site rule page source was not found');
const packaged = await build({ entryPoints: [new URL('site-rules-packaged.ts', root).pathname],
  bundle: true, write: false, format: 'iife', platform: 'browser', target: 'chrome120', minify: true });
output('site-rules-content.js', '// Generated from packages/shared/src/site-rules/page-script.ts. Do not edit.\n'
  + 'window.__yiqikanInstallSiteRules = function(snapshot) {\n'
  + body.replace('__SITE_RULE_SNAPSHOT_JSON__', 'snapshot').trim() + '\n};\n' + packaged.outputFiles[0].text);
const result = await build({
  entryPoints: [new URL('site-rules-background.ts', root).pathname],
  bundle: true, write: false, format: 'iife', platform: 'browser', target: 'chrome120', minify: true,
  legalComments: 'inline',
});
output('site-rules-background.js', '// Generated by scripts/sync-site-rules.mjs. Do not edit.\n' + result.outputFiles[0].text);
const requireShared = createRequire(new URL('../../../packages/shared/package.json', import.meta.url));
const curves = requireShared.resolve('@noble/curves/ed25519.js');
const hashes = createRequire(curves).resolve('@noble/hashes/sha2.js');
output('THIRD_PARTY_NOTICES.txt', 'Bundled site-rule verifier dependencies (generated).\n\n'
  + [curves, hashes].map(entry => {
    const directory = dirname(entry), pkg = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
    return pkg.name + '@' + pkg.version + '\n' + readFileSync(join(directory, 'LICENSE'), 'utf8').trim();
  }).join('\n\n') + '\n');
